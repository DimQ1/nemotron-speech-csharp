using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Android.App;
using Android.Content;
using Android.OS;
using Android.Runtime;
using Android.Views;
using Android.Widget;
using Microsoft.UI.Xaml.Media;
using Uno.UI.Hosting;

namespace VoiceType.Uno.Droid;

[global::Android.App.ApplicationAttribute(
    Label = "@string/ApplicationName",
    Icon = "@mipmap/icon",
    LargeHeap = true,
    HardwareAccelerated = true,
    Theme = "@style/Theme.App.Starting"
)]
public class Application : global::Uno.UI.Runtime.Android.NativeApplication
{
    // NOTE: App.InitializeLogging() is generated by the unoapp template only when
    // the Logging feature is enabled. VoiceType.Uno does not define it, so the
    // static constructor that calls it is omitted.

    public Application(IntPtr javaReference, JniHandleOwnership transfer)
        : base(javaReference, transfer)
    {
    }

    // Uno 7: the Android head builds its host like every other head (UnoPlatformHostBuilder).
    protected override UnoPlatformHost CreateHost() =>
        UnoPlatformHostBuilder.Create()
            .App(() => new App())
            .UseAndroid()
            .Build();

}

