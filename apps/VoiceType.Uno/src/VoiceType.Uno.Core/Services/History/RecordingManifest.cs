using System.Text.Json;
using System.Text.Json.Serialization;

namespace VoiceType.Uno.History;

/// <summary>Values of <see cref="TranscriptVersion.Kind"/>. Kept as strings so a newer kind round-trips.</summary>
public static class VersionKinds
{
    public const string Live = "live";
    public const string Rerecognized = "rerecognized";
    public const string Edited = "edited";
}

/// <summary>Values of <see cref="RecordingManifest.State"/>.</summary>
public static class RecordingStates
{
    /// <summary>Audio/transcript are still being written (a <c>.lock</c> file exists).</summary>
    public const string Recording = "recording";
    public const string Complete = "complete";
    /// <summary>Found unfinished on startup and finalized from the partial files.</summary>
    public const string Recovered = "recovered";
    /// <summary>Found unfinished on startup and could not be finalized (no audio, no transcript).</summary>
    public const string Incomplete = "incomplete";
}

/// <summary>Values of <see cref="TranslationInfo.Status"/>.</summary>
public static class TranslationStatuses
{
    public const string Complete = "complete";
    public const string Partial = "partial";
    public const string Failed = "failed";
}

/// <summary>Values of <see cref="TranscriptSegment.WordTiming"/>.</summary>
public static class WordTimingKinds
{
    public const string Estimated = "estimated";
    public const string Decoder = "decoder";
}

/// <summary>
/// <c>manifest.json</c> of one recording folder: metadata, transcript versions and
/// translations. The folder is the source of truth; any index is a cache.
/// </summary>
public sealed class RecordingManifest
{
    public const int CurrentSchema = 1;

    /// <summary>Number of transcript words used for the fallback title.</summary>
    public const int FallbackTitleWords = 8;

    public int Schema { get; set; } = CurrentSchema;

    /// <summary>6 hex chars; also the suffix of the folder name.</summary>
    public string Id { get; set; } = "";

    /// <summary>User-given title. Never overwritten by the auto-title job.</summary>
    public string? Title { get; set; }

    /// <summary>Title generated by Gemma (low-priority job).</summary>
    public string? AutoTitle { get; set; }

    public DateTimeOffset StartedAt { get; set; }
    public DateTimeOffset? EndedAt { get; set; }

    /// <summary>One of <see cref="RecordingStates"/>.</summary>
    public string State { get; set; } = RecordingStates.Complete;

    public RecordingMode Mode { get; set; } = new();

    /// <summary>Null when audio was never recorded.</summary>
    public AudioInfo? Audio { get; set; }

    public string? CurrentVersion { get; set; }
    public List<TranscriptVersion> Versions { get; set; } = [];
    public List<TranslationInfo> Translations { get; set; } = [];

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? ExtensionData { get; set; }

    [JsonIgnore]
    public TranscriptVersion? Current =>
        CurrentVersion is null ? null : Versions.Find(v => v.Id == CurrentVersion);

    /// <summary>True when an audio file is (supposed to be) present.</summary>
    [JsonIgnore]
    public bool HasAudio => Audio is { RemovedAt: null } && !string.IsNullOrEmpty(Audio.File);

    /// <summary>
    /// Title to show: user title, else auto title, else the first words of the
    /// current version, else a date-based placeholder.
    /// </summary>
    [JsonIgnore]
    public string EffectiveTitle => RecordingTitle.Effective(this);

    public TranscriptVersion? FindVersion(string versionId) => Versions.Find(v => v.Id == versionId);
    public TranslationInfo? FindTranslation(string translationId) => Translations.Find(t => t.Id == translationId);
}

public sealed class RecordingMode
{
    public bool InjectText { get; set; }
    public bool Translation { get; set; }

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? ExtensionData { get; set; }
}

public sealed class AudioInfo
{
    /// <summary>File name relative to the recording folder (e.g. <c>audio.ogg</c>).</summary>
    public string File { get; set; } = "";
    public string? Codec { get; set; }
    public int SampleRate { get; set; }
    public int Channels { get; set; } = 1;
    public int? Bitrate { get; set; }
    public double DurationSec { get; set; }
    public long Bytes { get; set; }

    /// <summary><c>AppSettings.AudioSource</c>: Mic | Loopback | Mix.</summary>
    public string? Source { get; set; }

    /// <summary>Muted stretches: no audio was written, the timeline stays continuous.</summary>
    public List<AudioGap> Gaps { get; set; } = [];

    /// <summary>Set when the audio was deleted (retention or by the user); text stays.</summary>
    public DateTimeOffset? RemovedAt { get; set; }

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? ExtensionData { get; set; }
}

public sealed class AudioGap
{
    public double AtSec { get; set; }
    public double WallSec { get; set; }
    public string? Reason { get; set; }

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? ExtensionData { get; set; }
}

/// <summary>An immutable transcript snapshot. Only <see cref="RecordingManifest.CurrentVersion"/> moves.</summary>
public sealed class TranscriptVersion
{
    public string Id { get; set; } = "";

    /// <summary>One of <see cref="VersionKinds"/>.</summary>
    public string Kind { get; set; } = VersionKinds.Live;

    /// <summary>Relative path, e.g. <c>transcripts/v1.json</c>.</summary>
    public string File { get; set; } = "";
    public DateTimeOffset CreatedAt { get; set; }

    public ModelInfo? Model { get; set; }
    public LanguageInfo? Language { get; set; }

    /// <summary>Everything that changes the recognition result (VAD, penalty, EP, chunk…).</summary>
    public Dictionary<string, JsonElement>? Settings { get; set; }
    public AppInfo? App { get; set; }
    public VersionStats? Stats { get; set; }

    /// <summary>For <see cref="VersionKinds.Edited"/>: the version the edit started from.</summary>
    public string? Parent { get; set; }

    /// <summary>Live version where the user typed into the text box during recording.</summary>
    public bool Edited { get; set; }

    /// <summary>First ~200 characters of the text, so lists need not load transcripts.</summary>
    public string? Excerpt { get; set; }

    [JsonExtensionData]
    public Dictionary<string, JsonElement>? ExtensionData { get; set; }
}

